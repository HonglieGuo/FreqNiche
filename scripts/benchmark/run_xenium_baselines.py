def run_validation_resolution_selection(
    methods: List[str],
    seeds: List[int] = SEEDS,
    device_str: str = "cuda" if torch.cuda.is_available() else "cpu",
) -> Dict[str, Any]:
    print("\n" + "=" * 85)
    print("PHASE 1: BASELINE UNSUPERVISED RESOLUTION SELECTION r* ON L6 VALIDATION")
    print(f"Methods: {methods} | Seeds: {seeds} | Centers: 10,000 | Folds: 10 | Bounds: {K_MIN} <= K <= {K_MAX}")
    print("=" * 85)

    device = torch.device(device_str)

    # 1. Load validation centers and bootstrap folds
    assert VAL_CENTERS_PATH.exists(), f"Missing {VAL_CENTERS_PATH}"
    assert VAL_FOLDS_PATH.exists(), f"Missing {VAL_FOLDS_PATH}"
    with open(VAL_CENTERS_PATH, "r", encoding="utf-8") as f:
        val_centers = json.load(f)
    with open(VAL_FOLDS_PATH, "r", encoding="utf-8") as f:
        folds = json.load(f)

    n_val = len(val_centers)
    assert n_val == 10000, f"Expected 10,000 val centers, got {n_val}"
    local_indices = [c["local_cell_idx"] for c in val_centers]

    # 2. Load L6 AnnData
    assert L6_H5AD_PATH.exists(), f"Missing {L6_H5AD_PATH}"
    print(f"Loading validation donor L6 ({L6_H5AD_PATH.name}) ...")
    a_l6 = ad.read_h5ad(L6_H5AD_PATH)
    coords_l6 = np.asarray(a_l6.obsm["spatial"], dtype=np.float32)

    # Slice the 10,000 validation centers
    coords_val = coords_l6[local_indices]
    raw_X = a_l6.X[local_indices]
    if sp.issparse(raw_X):
        X_val = raw_X.toarray().astype(np.float32)
    else:
        X_val = np.asarray(raw_X, dtype=np.float32)

    adata_val = ad.AnnData(
        X=X_val,
        obs={"sample_id": ["L6_val"] * n_val},
        var=a_l6.var.copy(),
        obsm={"spatial": coords_val}
    )

    selection_manifest: Dict[str, Any] = {
        "manifest_version": "2.0.0",
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "donor_validation": "L6",
        "n_val_centers": n_val,
        "n_folds": len(folds),
        "k_bounds": {"k_min": K_MIN, "k_max": K_MAX},
        "resolutions_grid": FROZEN_RESOLUTIONS,
        "seeds": seeds,
        "selected_r_star_per_method_and_seed": {},
        "details": {},
    }

    fold_names = [f"fold_{i}" for i in range(10)]
    fold_indices_list = [np.array(folds[fname]["indices_in_val_centers"], dtype=np.int64) for fname in fold_names]
    n_bootstraps = len(fold_indices_list)

    for m in methods:
        if m not in BASELINE_EXTRACTORS:
            continue

        selection_manifest["selected_r_star_per_method_and_seed"][m] = {}
        selection_manifest["details"][m] = {}

        fn = BASELINE_EXTRACTORS[m]

        for s in seeds:
            print(f"\n>>> [Val Selection] Method: {m} | Seed: {s} ...")
            emb, elapsed, peak_ram, peak_vram = profile_call(
                fn, adata_val, seed=s, device=device
            )
            print(f"    Extracted embedding shape: {emb.shape} in {elapsed:.2f}s (RAM: {peak_ram:.1f} MB, VRAM: {peak_vram:.1f} MB)")

            scores_per_res = {}
            mean_k_per_res = {}
            pair_aris_per_res = {}

            adata_full = ad.AnnData(X=emb.copy())
            sc.pp.neighbors(adata_full, n_neighbors=15, use_rep="X", random_state=s)

            for res in FROZEN_RESOLUTIONS:
                clusterings = []
                for b in range(n_bootstraps):
                    sub_idx = fold_indices_list[b]
                    z_sub = emb[sub_idx]
                    ad_sub = ad.AnnData(X=z_sub.copy())
                    sc.pp.neighbors(ad_sub, n_neighbors=15, use_rep="X", random_state=s + b)
                    sc.tl.leiden(ad_sub, resolution=res, key_added="leiden", random_state=s + b)
                    clusterings.append(ad_sub.obs["leiden"].to_numpy().astype(int))

                mean_k = float(np.mean([len(np.unique(c)) for c in clusterings]))
                mean_k_per_res[res] = mean_k

                pair_aris = []
                for i in range(n_bootstraps):
                    for j in range(i + 1, n_bootstraps):
                        idx_i = fold_indices_list[i]
                        idx_j = fold_indices_list[j]
                        common_cells, pos_i, pos_j = np.intersect1d(idx_i, idx_j, return_indices=True)
                        if len(common_cells) > 10:
                            pair_aris.append(float(adjusted_rand_score(clusterings[i][pos_i], clusterings[j][pos_j])))

                stability = float(np.mean(pair_aris)) if pair_aris else 0.0
                scores_per_res[res] = stability
                pair_aris_per_res[res] = pair_aris
                print(f"    r={res}: mean(K)={mean_k:.1f}, stability(mean ARI)={stability:.4f}")

            # Strict protocol: K_MIN <= mean(K) <= K_MAX, maximize stability
            valid_res = [r for r in FROZEN_RESOLUTIONS if K_MIN <= mean_k_per_res[r] <= K_MAX]
            if valid_res:
                best_res = max(valid_res, key=lambda r: scores_per_res[r])
            else:
                # Fallback: candidate closest to [K_MIN, K_MAX] interval
                diffs = {r: min(abs(mean_k_per_res[r] - K_MIN), abs(mean_k_per_res[r] - K_MAX)) for r in FROZEN_RESOLUTIONS}
                best_res = min(diffs, key=diffs.get)

            print(f"  ==> Selected r* for {m} (Seed {s}): r*={best_res} (mean K={mean_k_per_res[best_res]:.1f}, stability={scores_per_res[best_res]:.4f})")

            # Full validation clustering at r*
            sc.tl.leiden(adata_full, resolution=best_res, key_added="leiden_star", random_state=s)
            labels_star = adata_full.obs["leiden_star"].to_numpy().astype(int)
            full_k = len(np.unique(labels_star))
            erank, var_spec = compute_effective_rank(emb)

            selection_manifest["selected_r_star_per_method_and_seed"][m][str(s)] = best_res
            selection_manifest["details"][m][str(s)] = {
                "r_star": best_res,
                "mean_k_at_r_star": mean_k_per_res[best_res],
                "stability_score": scores_per_res[best_res],
                "full_val_k": full_k,
                "effective_rank": erank,
                "variance_spectrum": var_spec,
                "grid_summary": {
                    str(r): {"mean_k": mean_k_per_res[r], "stability": scores_per_res[r]}
                    for r in FROZEN_RESOLUTIONS
                },
            }

    tmp_path = RESOLUTION_SELECTION_PATH.with_suffix(".tmp.json")
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(selection_manifest, f, indent=2)
    os.replace(tmp_path, RESOLUTION_SELECTION_PATH)
    print(f"\nSaved and locked baseline resolution selection to {RESOLUTION_SELECTION_PATH}")
    return selection_manifest


