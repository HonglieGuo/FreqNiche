                    f"\n{'!' * 85}\n"
                    f"FATAL ASSET IMMUTABILITY VIOLATION: Formal embedding already exists:\n"
                    f"  {emb_file}\n"
                    f"Overwriting formal benchmark assets is strictly prohibited by audit policy.\n"
                    f"{'!' * 85}"
