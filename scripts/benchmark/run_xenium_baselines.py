def _extractor_worker_entry(
    method_name: str,
    h5ad_path: str,
    seed: int,
    device_str: str,
    out_emb_path: str,
    result_queue: Any,
):
    """
    Child process worker executing baseline feature extraction with hardware-level memory fraction.
    """
    try:
        # Hardware-level memory allocation cap in PyTorch C++ allocator
        if torch.cuda.is_available() and device_str.startswith("cuda"):
            total_vram_mb = torch.cuda.get_device_properties(0).total_memory / (1024 * 1024)
            fraction = min(1.0, VRAM_HARD_LIMIT_MIB / total_vram_mb)
            torch.cuda.set_per_process_memory_fraction(fraction, 0)

        adata_in = ad.read_h5ad(h5ad_path)
        fn = BASELINE_EXTRACTORS[method_name]
        device = torch.device(device_str)

        emb = fn(adata_in, seed=seed, device=device)
        assert np.all(np.isfinite(emb)), f"Non-finite embedding generated by {method_name}!"
        np.save(out_emb_path, emb)
        result_queue.put({"status": "SUCCESS", "shape": list(emb.shape), "error": None})
    except Exception as e:
        result_queue.put({"status": "FAILED", "shape": None, "error": str(e)})


def profile_call(
    fn_or_name: Any,
    adata_in: ad.AnnData,
    seed: int = 42,
    device: Optional[torch.device] = None,
    **kwargs,
) -> Tuple[np.ndarray, float, float, float]:
    """
    Executes baseline feature extraction in an isolated child process with:
    1. Hardware-level PyTorch C++ memory fraction cap (16,384 MiB limit).
    2. Parent process active 10ms supervisor sending SIGKILL if child VRAM > 16,384 MiB.
    3. Real-time dynamic host RSS tracking of child process.
    Returns: (embedding, runtime_sec, peak_ram_mb, peak_vram_mb)
    """
    import multiprocessing as mp

    method_name = fn_or_name if isinstance(fn_or_name, str) else getattr(fn_or_name, "__name__", str(fn_or_name))
    for k, v in BASELINE_EXTRACTORS.items():
        if v == fn_or_name:
            method_name = k
            break

    device_str = "cuda" if (device is not None and device.type == "cuda") or (device is None and torch.cuda.is_available()) else "cpu"

    temp_id = f"{os.getpid()}_{time.time_ns()}"
    temp_h5ad = CACHE_DIR / f"temp_in_{temp_id}.h5ad"
    temp_out = CACHE_DIR / f"temp_out_{temp_id}.npy"

    try:
        adata_in.write_h5ad(temp_h5ad)

        ctx = mp.get_context("spawn")
        result_queue = ctx.Queue()
        proc = ctx.Process(
            target=_extractor_worker_entry,
            args=(method_name, str(temp_h5ad), seed, device_str, str(temp_out), result_queue)
        )

        t0 = time.time()
        proc.start()
        pid = proc.pid

        peak_ram_mb = 0.0
        peak_vram_mb = 0.0
        tripped = False

        # Parent process active supervisor loop
        while proc.is_alive():
            try:
                p_handle = psutil.Process(pid)
                child_rss = p_handle.memory_info().rss / (1024 * 1024)
                if child_rss > peak_ram_mb:
                    peak_ram_mb = child_rss

                if torch.cuda.is_available() and device_str.startswith("cuda"):
                    # Query GPU memory of child PID directly via nvidia-smi
                    out = os.popen(f"nvidia-smi --query-compute-apps=pid,used_memory --format=csv,noheader,nounits 2>/dev/null").read()
                    for line in out.strip().split("\n"):
                        if line.strip():
                            parts = line.split(",")
                            if len(parts) == 2 and int(parts[0].strip()) == pid:
                                gpu_mem = float(parts[1].strip())
                                if gpu_mem > peak_vram_mb:
                                    peak_vram_mb = gpu_mem

                    # Active 16GB Hard Kill Guard
                    if peak_vram_mb > VRAM_HARD_LIMIT_MIB:
                        tripped = True
                        print(f"\n[ACTIVE 16GB VRAM HARD KILL] Child PID {pid} ({method_name}) VRAM={peak_vram_mb:.1f} MiB > limit {VRAM_HARD_LIMIT_MIB} MiB! Actively sending SIGKILL...")
                        proc.kill()
                        proc.join(timeout=2.0)
                        break
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                break
            time.sleep(0.05)

        proc.join()
        elapsed = time.time() - t0

        if tripped:
            raise MemoryError(
                f"ACTIVE 16GB VRAM KILL GUARD TRIPPED: Method '{method_name}' exceeded {VRAM_HARD_LIMIT_MIB} MiB (peak: {peak_vram_mb:.1f} MiB)! "
                "Process was actively terminated via SIGKILL to protect GPU and system."
            )

        worker_res = None
        if not result_queue.empty():
            worker_res = result_queue.get()

        if worker_res is None or worker_res["status"] != "SUCCESS":
            err_msg = worker_res["error"] if worker_res else f"Process terminated with exit code {proc.exitcode}"
            raise RuntimeError(f"Feature extraction failed for '{method_name}': {err_msg}")

        emb = np.load(temp_out)
        return emb, elapsed, peak_ram_mb, peak_vram_mb
    finally:
        if temp_h5ad.exists():
            temp_h5ad.unlink()
        if temp_out.exists():
            temp_out.unlink()


