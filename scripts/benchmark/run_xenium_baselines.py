def run_multi_tier_smoke_guarded(
    methods: List[str],
    scales: List[int] = [1000, 5000, 10000],
    device_str: str = "cuda" if torch.cuda.is_available() else "cpu",
) -> Dict[str, Any]:
    print("\n" + "=" * 85)
    print("PHASE 3: MULTI-TIER RESOURCE SMOKE & SCALABILITY TEST (CONTINUOUS POLLING)")
    print(f"Methods: {methods} | Scales: {scales} | Device: {device_str}")
    print("=" * 85)

    device = torch.device(device_str)
    assert L1_H5AD_PATH.exists(), f"Missing L1 sample: {L1_H5AD_PATH}"
    print(f"Loading metadata from {L1_H5AD_PATH.name} ...")
    a_full = ad.read_h5ad(L1_H5AD_PATH, backed="r")
    coords_all = np.asarray(a_full.obsm["spatial"], dtype=np.float32)
    center_pt = np.median(coords_all, axis=0, keepdims=True)
    tree = cKDTree(coords_all)

    telemetry: Dict[str, Any] = {
        "benchmark": "Xenium_5K_Baseline_MultiTier_Smoke",
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "device": device_str,
        "scales": scales,
        "results": {},
    }

    for scale in scales:
        print(f"\n" + "-" * 70)
        print(f"--- TESTING SCALE: {scale:,} CELLS (5,001 Genes) ---")
        print("-" * 70)

        _, patch_indices = tree.query(center_pt, k=scale)
        patch_indices = np.sort(patch_indices[0])
        coords_patch = coords_all[patch_indices]

        raw_X = a_full.X[patch_indices]
        if sp.issparse(raw_X):
            X_dense = raw_X.toarray().astype(np.float32)
        else:
            X_dense = np.asarray(raw_X, dtype=np.float32)

        adata_patch = ad.AnnData(
            X=X_dense,
            obs={"sample_id": ["L1_patch"] * scale},
            var=a_full.var.copy(),
            obsm={"spatial": coords_patch}
        )

        for m in methods:
            if m not in BASELINE_EXTRACTORS:
                continue

            print(f"\n[Smoke] Method: {m} (Scale={scale:,}) ...")
            fn = BASELINE_EXTRACTORS[m]

            status = "PASS"
            err = None
            emb = None
            k_clusters = None
            runtime = 0.0
            peak_ram = 0.0
            peak_vram = 0.0

            try:
                emb, runtime, peak_ram, peak_vram = profile_call(
                    fn, adata_patch, seed=42, device=device
                )
                assert emb.shape[0] == scale, f"Expected {scale} rows, got {emb.shape}"
                assert np.all(np.isfinite(emb)), "Non-finite embeddings detected!"

                ad_emb = ad.AnnData(X=emb)
                sc.pp.neighbors(ad_emb, n_neighbors=15, use_rep="X", random_state=42)
                sc.tl.leiden(ad_emb, resolution=0.5, key_added="leiden", random_state=42)
                k_clusters = len(np.unique(ad_emb.obs["leiden"]))

            except Exception as e:
                status = "FAIL"
                err = str(e)
                print(f"  [FAIL] {m} failed at scale {scale}: {e}")

            res_entry = {
                "method": m,
                "scale": scale,
                "status": status,
                "runtime_sec": round(runtime, 2),
                "peak_ram_mb": round(peak_ram, 1),
                "peak_vram_mb": round(peak_vram, 1),
                "embedding_dim": int(emb.shape[1]) if emb is not None else None,
                "k_clusters_r05": k_clusters,
                "error": err,
            }

            key = f"{m}@{scale}"
            telemetry["results"][key] = res_entry

            print(f"  Result: {status} | Time: {runtime:.2f}s | Peak Dynamic RAM: {peak_ram:.1f} MB | Peak VRAM: {peak_vram:.1f} MB | Emb: {emb.shape if emb is not None else None} | K: {k_clusters}")

    telemetry_path = SMOKE_DIR / "smoke_telemetry.json"
    with open(telemetry_path, "w", encoding="utf-8") as f:
        json.dump(telemetry, f, indent=2)
    print(f"\nSaved smoke telemetry to {telemetry_path}")
    return telemetry


