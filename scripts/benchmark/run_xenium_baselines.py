def extract_raw_pca(adata_in: ad.AnnData, n_components: int = 50, seed: int = 42, **kwargs) -> np.ndarray:
    ad_work = adata_in.copy()
    sc.pp.normalize_total(ad_work, target_sum=1e4)
    sc.pp.log1p(ad_work)
    X = ad_work.X
    if sp.issparse(X):
        X = X.toarray()
    X = np.asarray(X, dtype=np.float32)
    pca = PCA(n_components=n_components, random_state=seed)
    return pca.fit_transform(X).astype(np.float32)


def extract_px_resdiff(adata_in: ad.AnnData, n_components: int = 50, seed: int = 42, **kwargs) -> np.ndarray:
    ad_work = adata_in.copy()
    sc.pp.normalize_total(ad_work, target_sum=1e4)
    sc.pp.log1p(ad_work)

    coords = np.asarray(ad_work.obsm["spatial"], dtype=np.float32)
    sample_ids = np.array(["sample"] * len(coords))
    P, _ = build_global_spatial_graph(
        coords=coords, sample_ids=sample_ids, radius=RADIUS_UM, sigma=SIGMA_UM, max_neighbors=None
    )

    X = ad_work.X
    if sp.issparse(X):
        X = X.toarray()
    X = np.asarray(X, dtype=np.float32)

    PX = P.dot(X).astype(np.float32)
    H = X - PX
    features = np.concatenate([PX, H], axis=1)

    pca = PCA(n_components=n_components, random_state=seed)
    return pca.fit_transform(features).astype(np.float32)


